  defp load_payload do
    Presenter.state_payload(orchestrator(), snapshot_timeout_ms())
  end

  defp orchestrator do
    Endpoint.config(:orchestrator) || SymphonyElixir.Orchestrator
  end

  defp snapshot_timeout_ms do
    Endpoint.config(:snapshot_timeout_ms) || 15_000
  end

  defp completed_runtime_seconds(payload) do
    payload.codex_totals.seconds_running || 0
  end

  defp total_runtime_seconds(payload, now) do
    completed_runtime_seconds(payload) +
      Enum.reduce(payload.running, 0, fn entry, total ->
        total + runtime_seconds_from_started_at(entry.started_at, now)
      end)
  end

  defp format_runtime_and_turns(started_at, turn_count, now) when is_integer(turn_count) and turn_count > 0 do
    "#{format_runtime_seconds(runtime_seconds_from_started_at(started_at, now))} / #{turn_count}"
  end

  defp format_runtime_and_turns(started_at, _turn_count, now),
    do: format_runtime_seconds(runtime_seconds_from_started_at(started_at, now))

  defp format_runtime_seconds(seconds) when is_number(seconds) do
    whole_seconds = max(trunc(seconds), 0)
    mins = div(whole_seconds, 60)
    secs = rem(whole_seconds, 60)
    "#{mins}m #{secs}s"
  end

  defp runtime_seconds_from_started_at(%DateTime{} = started_at, %DateTime{} = now) do
    DateTime.diff(now, started_at, :second)
  end

  defp runtime_seconds_from_started_at(started_at, %DateTime{} = now) when is_binary(started_at) do
    case DateTime.from_iso8601(started_at) do
      {:ok, parsed, _offset} -> runtime_seconds_from_started_at(parsed, now)
      _ -> 0
    end
  end

  defp runtime_seconds_from_started_at(_started_at, _now), do: 0

  defp running_summary_items(entry, now) do
    [
      {"任务", task_summary(entry)},
      {"当前进度", current_progress_summary(entry, now)},
      {"卡点", blocker_summary(entry)},
      {"下一步", next_plan_summary(entry)},
      {"最近活动", last_activity_summary(entry)},
      {"工作区", workspace_summary(entry)}
    ]
  end

  defp task_summary(entry) do
    issue = Map.get(entry, :issue) || %{}
    title = issue |> Map.get(:title) |> blank_to_nil()
    description = issue |> Map.get(:description) |> blank_to_nil()

    cond do
      title && description -> "#{title}: #{truncate_summary(description)}"
      title -> title
      description -> truncate_summary(description)
      true -> "暂无任务标题和描述。"
    end
  end

  defp current_progress_summary(entry, _now) do
    task_detail(entry, :progress) || "等待 agent 首次进度事件。"
  end

  defp blocker_summary(entry) do
    task_detail(entry, :blocker) || "当前无真实卡点事件。"
  end

  defp next_plan_summary(entry) do
    task_detail(entry, :plan) || "等待 agent 计划事件。"
  end

  defp task_detail(entry, key) do
    details = Map.get(entry, :task_details) || %{}

    details
    |> Map.get(key)
    |> blank_to_nil()
  end

  defp last_activity_summary(entry) do
    activity = entry.last_message || to_string(entry.last_event || "n/a")

    case entry.last_event_at do
      nil -> activity
      last_event_at -> "#{activity} · #{last_event_at}"
    end
  end

  defp workspace_summary(entry) do
    host = entry.worker_host || "本地"
    path = entry.workspace_path || "未上报"

    "#{host} · #{path}"
  end

  defp blank_to_nil(value) when is_binary(value) do
    value = String.trim(value)
    if value == "", do: nil, else: value
  end

  defp blank_to_nil(_value), do: nil

  defp truncate_summary(value) when byte_size(value) > 240 do
    value
    |> String.slice(0, 240)
    |> String.trim()
    |> Kernel.<>("...")
  end

  defp truncate_summary(value), do: value

  defp running_detail_expanded?(expanded_running_details, entry) do
    MapSet.member?(expanded_running_details, running_entry_key(entry))
  end

  defp running_entry_key(entry) do
    to_string(entry.issue_id || entry.issue_identifier || entry.session_id || "unknown")
  end

  defp prune_expanded_running_details(expanded_running_details, running_entries) do
    running_keys =
      running_entries
      |> Enum.map(&running_entry_key/1)
      |> MapSet.new()

    MapSet.intersection(expanded_running_details, running_keys)
  end

  defp format_int(value) when is_integer(value) do
    value
    |> Integer.to_string()
    |> String.reverse()
    |> String.replace(~r/.{3}(?=.)/, "\\0,")
    |> String.reverse()
  end

  defp format_int(_value), do: "n/a"

  defp state_badge_class(state) do
    base = "state-badge"
    normalized = state |> to_string() |> String.downcase()

    cond do
      String.contains?(normalized, ["progress", "running", "active"]) -> "#{base} state-badge-active"
      String.contains?(normalized, ["blocked", "error", "failed"]) -> "#{base} state-badge-danger"
      String.contains?(normalized, ["todo", "queued", "pending", "retry"]) -> "#{base} state-badge-warning"
      true -> base
    end
  end

  defp schedule_runtime_tick do
    Process.send_after(self(), :runtime_tick, @runtime_tick_ms)
  end

  defp pretty_value(nil), do: "n/a"
  defp pretty_value(value), do: inspect(value, pretty: true, limit: :infinity)
end
